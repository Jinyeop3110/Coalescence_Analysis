def add_formatting(writer: pd.ExcelWriter) -> None:
    wb = writer.book
    header_fill = PatternFill("solid", fgColor="1F4E78")
    header_font = Font(color="FFFFFF", bold=True)

    for ws in wb.worksheets:
        ws.freeze_panes = "A2"
        ws.auto_filter.ref = ws.dimensions
        for cell in ws[1]:
            cell.fill = header_fill
            cell.font = header_font
            cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        for column_cells in ws.columns:
            letter = get_column_letter(column_cells[0].column)
            max_len = max(len(str(cell.value)) if cell.value is not None else 0 for cell in column_cells[:200])
            ws.column_dimensions[letter].width = min(max(max_len + 2, 10), 35)
        for row in ws.iter_rows(min_row=2):
            for cell in row:
                if isinstance(cell.value, float):
                    cell.number_format = "0.000"

    if "SC_vs_CC" in wb.sheetnames:
        ws = wb["SC_vs_CC"]
        chart = BarChart()
        chart.type = "col"
        chart.style = 10
        chart.title = "Mean pH day7: SC vs CC"
        chart.y_axis.title = "pH"
        chart.x_axis.title = "origin + medium"
        headers = [cell.value for cell in ws[1]]
        try:
            sc_col = headers.index("pH_day7_SC_mean") + 1
            cc_col = headers.index("pH_day7_CC_mean") + 1
            data = Reference(ws, min_col=sc_col, max_col=cc_col, min_row=1, max_row=ws.max_row)
            cats = Reference(ws, min_col=2, min_row=2, max_row=ws.max_row)
            chart.add_data(data, titles_from_data=True)
            chart.set_categories(cats)
            chart.height = 7
            chart.width = 14
            ws.add_chart(chart, "B10")
        except ValueError:
            pass


def main() -> None:
    community_samples = load_community_samples()
    community_summary = summarize_communities(community_samples)
    sc_vs_cc = compare_single_vs_coalesced(community_summary)
    monoculture_isolates = load_monoculture_isolates()
    monoculture_summary = summarize_monocultures(monoculture_isolates)

    with pd.ExcelWriter(OUT_XLSX, engine="openpyxl") as writer:
        source_notes().to_excel(writer, sheet_name="sources", index=False)
        community_samples.to_excel(writer, sheet_name="community_samples", index=False)
        community_summary.to_excel(writer, sheet_name="community_summary", index=False)
        sc_vs_cc.to_excel(writer, sheet_name="SC_vs_CC", index=False)
        monoculture_isolates.to_excel(writer, sheet_name="monoculture_isolates", index=False)
        monoculture_summary.to_excel(writer, sheet_name="monoculture_summary", index=False)
        add_formatting(writer)

    print(f"Wrote {OUT_XLSX}")
    print(f"community_samples: {len(community_samples)} rows")
    print(f"monoculture_isolates: {len(monoculture_isolates)} rows")


if __name__ == "__main__":
    main()
